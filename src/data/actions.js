// All data mutations used by the UI. Components never edit AppData directly.

import { update, replaceAll } from './store.js';
import { emptyData, FALLBACK_EXPENSE_CATEGORY, FALLBACK_INCOME_CATEGORY } from './schema.js';
import { newId } from '../lib/ids.js';
import { todayISO } from '../lib/dates.js';
import { generateRecurring } from './recurring.js';

const stamp = () => new Date().toISOString();

function upsert(list, item, prefix) {
  if (item.id && list.some((x) => x.id === item.id)) {
    return list.map((x) => (x.id === item.id ? { ...x, ...item, updatedAt: stamp() } : x));
  }
  return [...list, { ...item, id: item.id || newId(prefix), createdAt: stamp(), updatedAt: stamp() }];
}

// ---------------- Students ----------------
export const saveStudent = (student) =>
  update((d) => ({ ...d, students: upsert(d.students, student, 'stu') }));

export const setStudentStatus = (id, status) =>
  update((d) => ({ ...d, students: d.students.map((s) => (s.id === id ? { ...s, status, updatedAt: stamp() } : s)) }));

/** Deleting a student also deletes their Preply records (the UI warns first). */
export const deleteStudent = (id) =>
  update((d) => ({
    ...d,
    students: d.students.filter((s) => s.id !== id),
    preplyEntries: d.preplyEntries.filter((e) => e.studentId !== id),
  }));

// ---------------- Preply records & payouts ----------------
export const savePreplyEntry = (entry) =>
  update((d) => ({ ...d, preplyEntries: upsert(d.preplyEntries, entry, 'ppl') }));
export const deletePreplyEntry = (id) =>
  update((d) => ({ ...d, preplyEntries: d.preplyEntries.filter((e) => e.id !== id) }));
export const setPreplyEntryStatus = (ids, status) => {
  const set = new Set(ids);
  return update((d) => ({
    ...d,
    preplyEntries: d.preplyEntries.map((e) => (set.has(e.id) ? { ...e, status, updatedAt: stamp() } : e)),
  }));
};
export const savePayout = (p) => update((d) => ({ ...d, payouts: upsert(d.payouts, p, 'pay') }));
export const deletePayout = (id) => update((d) => ({ ...d, payouts: d.payouts.filter((p) => p.id !== id) }));

// ---------------- Other income ----------------
export const saveIncome = (rec) => update((d) => ({ ...d, otherIncome: upsert(d.otherIncome, rec, 'inc') }));
export const deleteIncome = (id) => update((d) => ({ ...d, otherIncome: d.otherIncome.filter((r) => r.id !== id) }));

// ---------------- Expenses ----------------
export const saveExpense = (rec) => update((d) => ({ ...d, expenses: upsert(d.expenses, rec, 'exp') }));
export const deleteExpense = (id) => update((d) => ({ ...d, expenses: d.expenses.filter((r) => r.id !== id) }));

// ---------------- Recurring rules ----------------
/** Create a rule and immediately generate whatever is already due. */
export const createRecurring = (rule) =>
  update((d) => {
    const withRule = {
      ...d,
      recurring: [...d.recurring, { ...rule, id: newId('rec'), generatedKeys: [], createdAt: stamp() }],
    };
    return generateRecurring(withRule).data;
  });

/**
 * Edit a rule. Changes apply to future occurrences; records dated after today
 * that were generated by the rule (e.g. this month's expected income) are
 * updated too, past records stay untouched.
 */
export const updateRecurring = (rule) =>
  update((d) => {
    const today = todayISO();
    const t = rule.template;
    const patch = (r) =>
      r.recurringId === rule.id && r.date > today
        ? { ...r, ...t, id: r.id, date: r.date, ...(r.status ? { status: r.status } : {}), updatedAt: stamp() }
        : r;
    const next = {
      ...d,
      recurring: d.recurring.map((r) => (r.id === rule.id ? { ...r, ...rule } : r)),
      expenses: d.expenses.map(patch),
      otherIncome: d.otherIncome.map(patch),
    };
    return generateRecurring(next).data;
  });

/** Stop a rule from today on and remove its not-yet-due future records. */
export const stopRecurring = (id) =>
  update((d) => {
    const today = todayISO();
    const fut = (r) => !(r.recurringId === id && r.date > today);
    return {
      ...d,
      recurring: d.recurring.map((r) => (r.id === id ? { ...r, endDate: today } : r)),
      expenses: d.expenses.filter(fut),
      otherIncome: d.otherIncome.filter(fut),
    };
  });

/** Delete the rule only; records already created are kept as normal records. */
export const deleteRecurring = (id) =>
  update((d) => ({
    ...d,
    recurring: d.recurring.filter((r) => r.id !== id),
    expenses: d.expenses.map((r) => (r.recurringId === id ? { ...r, recurringId: null } : r)),
    otherIncome: d.otherIncome.map((r) => (r.recurringId === id ? { ...r, recurringId: null } : r)),
  }));

// ---------------- Categories ----------------
export const saveCategory = (kind, cat) =>
  update((d) => {
    const key = kind === 'expense' ? 'expenseCategories' : 'incomeCategories';
    const list = d[key];
    const next = cat.id && list.some((c) => c.id === cat.id)
      ? list.map((c) => (c.id === cat.id ? { ...c, ...cat } : c))
      : [...list, { ...cat, id: newId(kind === 'expense' ? 'cat' : 'inc') }];
    return { ...d, [key]: next };
  });

/** Delete a category; its records move to "Other". */
export const deleteCategory = (kind, id) =>
  update((d) => {
    if (kind === 'expense') {
      if (id === FALLBACK_EXPENSE_CATEGORY) return d;
      const { [id]: _drop, ...budgets } = d.settings.categoryBudgets;
      return {
        ...d,
        expenseCategories: d.expenseCategories.filter((c) => c.id !== id),
        expenses: d.expenses.map((x) => (x.categoryId === id ? { ...x, categoryId: FALLBACK_EXPENSE_CATEGORY } : x)),
        recurring: d.recurring.map((r) =>
          r.template.categoryId === id ? { ...r, template: { ...r.template, categoryId: FALLBACK_EXPENSE_CATEGORY } } : r
        ),
        settings: { ...d.settings, categoryBudgets: budgets },
      };
    }
    if (id === FALLBACK_INCOME_CATEGORY) return d;
    return {
      ...d,
      incomeCategories: d.incomeCategories.filter((c) => c.id !== id),
      otherIncome: d.otherIncome.map((x) => (x.categoryId === id ? { ...x, categoryId: FALLBACK_INCOME_CATEGORY } : x)),
      recurring: d.recurring.map((r) =>
        r.kind === 'income' && r.template.categoryId === id
          ? { ...r, template: { ...r.template, categoryId: FALLBACK_INCOME_CATEGORY } }
          : r
      ),
    };
  });

export const restoreDefaultCategories = () =>
  update((d) => {
    const fresh = emptyData();
    const have = new Set(d.expenseCategories.map((c) => c.id));
    return { ...d, expenseCategories: [...d.expenseCategories, ...fresh.expenseCategories.filter((c) => !have.has(c.id))] };
  });

// ---------------- Settings & exchange rate ----------------
export const updateSettings = (patch) => update((d) => ({ ...d, settings: { ...d.settings, ...patch } }));
export const setCategoryBudget = (categoryId, amount) =>
  update((d) => {
    const budgets = { ...d.settings.categoryBudgets };
    if (Number(amount) > 0) budgets[categoryId] = Number(amount);
    else delete budgets[categoryId];
    return { ...d, settings: { ...d.settings, categoryBudgets: budgets } };
  });
export const saveExchange = (exchange) => update((d) => ({ ...d, exchange }));

// ---------------- Whole-dataset operations ----------------
export const importData = (raw) => replaceAll(raw);
/** Reset everything except the cached exchange rate. */
export const resetAll = () => {
  return update((d) => ({ ...emptyData(), exchange: d.exchange }));
};
